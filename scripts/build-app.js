// Packages the web app into www/ for the iPhone app (Capacitor's webDir).
// The website and the app share every file except config.js, which here
// points the app at the API server instead of its own origin.
//
// Usage: npm run app:build            (production API)
//        DORMIE_API=http://localhost:8017 npm run app:build   (local dev server, for the simulator)
import { cp, mkdir, rm, writeFile } from 'node:fs/promises';

const root = new URL('..', import.meta.url).pathname;
const out = `${root}www/`;
const api = (process.env.DORMIE_API || 'https://dormie-gold.vercel.app').replace(/\/$/, '');
const files = ['index.html', 'app.js', 'auth.js', 'store.js', 'nassau.js', 'vendor'];

await rm(out, { recursive: true, force: true });
await mkdir(out);
for (const f of files) await cp(`${root}${f}`, `${out}${f}`, { recursive: true });
await writeFile(`${out}config.js`, `// Generated by scripts/build-app.js\nexport const API_BASE = ${JSON.stringify(api)};\n`);
console.log(`www/ built for ${api}`);
